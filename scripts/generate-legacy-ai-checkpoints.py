#!/usr/bin/env python3
"""Generate immutable Hoon checkpoints from an explicit nockscan source artifact.

Offline: python3 scripts/generate-legacy-ai-checkpoints.py --source SOURCE.json
Refetch: python3 scripts/generate-legacy-ai-checkpoints.py --fetch-source SOURCE.json
Check: add --check to compare the root and every chunk without writing any files.
The source includes the two neighboring blocks solely to authenticate the interval's
parent links. Normal builds do not invoke this script or access the network.
"""

import argparse
import csv
import datetime
import hashlib
import io
import json
from pathlib import Path
import re
import urllib.request

FIRST = 126000
PAST_LAST = 154500
P = 2**64 - 2**32 + 1
ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
NORMALIZED_SHA256 = "c91f068b83e41fc37982704e0151cb21f25e8c11995d9ca9d02fb30f8a8fa426"
SOURCE = "https://nockscan.com/api"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "hoon/dat/legacy-ai-checkpoints.hoon"
CHUNK_SIZE = 1000
CHUNK_DIRECTORY = "legacy-ai-checkpoint-chunks"
CHUNK_NAME = re.compile(r"heights-[0-9]{6}-[0-9]{6}\.hoon\Z")
CHUNK_HEADER = "::  Generated by scripts/generate-legacy-ai-checkpoints.py; owned literal chunk.\n"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def encode(value):
    result = ""
    while value:
        value, digit = divmod(value, 58)
        result = ALPHABET[digit] + result
    return result or "1"


def limbs(text):
    require(isinstance(text, str) and bool(text), "empty digest")
    value = 0
    for char in text:
        value = value * 58 + ALPHABET.index(char)
    require(encode(value) == text, "noncanonical base58 digest: " + text)
    result = []
    for _ in range(5):
        value, digit = divmod(value, P)
        result.append(digit)
    require(value == 0 and all(0 <= digit < P for digit in result),
            "digest exceeds five Goldilocks limbs: " + text)
    require(encode(sum(digit * P**i for i, digit in enumerate(result))) == text,
            "digest limb roundtrip failed")
    return result


def normalized_digest(blocks):
    text = "".join(f"{b['height']}\t{b['hash']}\t{b['parent']}\n" for b in blocks)
    return hashlib.sha256(text.encode("ascii")).hexdigest()


def fetch_source():
    blocks = []
    pages = []
    for start in range(FIRST - 1, PAST_LAST + 1, 1000):
        end = min(start + 999, PAST_LAST)
        url = f"{SOURCE}/v1/export-blocks?from={start}&to={end}"
        with urllib.request.urlopen(url, timeout=60) as response:
            require(response.url.startswith(SOURCE + "/"), "unexpected export redirect")
            raw = response.read()
        rows = list(csv.DictReader(io.StringIO(raw.decode("utf-8"))))
        require([int(row["height"]) for row in rows] == list(range(start, end + 1)),
                "export page has unexpected height coverage")
        blocks.extend({"height": int(row["height"]), "hash": row["hash"],
                       "parent": row["parent"]} for row in rows)
        pages.append({"url": url, "csv_sha256": hashlib.sha256(raw).hexdigest()})
    return {"source": SOURCE, "retrieved_date": datetime.date.today().isoformat(),
            "start_height": FIRST - 1, "end_height": PAST_LAST, "count": len(blocks),
            "normalized_tsv_sha256": normalized_digest(blocks),
            "pages": pages, "blocks": blocks}


def validate(source):
    require(source["source"] == SOURCE, "unexpected canonical source")
    datetime.date.fromisoformat(source["retrieved_date"])
    require((source["start_height"], source["end_height"], source["count"])
            == (FIRST - 1, PAST_LAST, PAST_LAST - FIRST + 2), "invalid source interval")
    blocks = source["blocks"]
    require([b["height"] for b in blocks] == list(range(FIRST - 1, PAST_LAST + 1)),
            "source must contain every height in increasing order, including neighbors")
    require(len({b["hash"] for b in blocks}) == len(blocks), "duplicate block IDs")
    for index, block in enumerate(blocks):
        limbs(block["hash"])
        limbs(block["parent"])
        if index:
            require(block["parent"] == blocks[index - 1]["hash"], "broken parent chain")
    require(normalized_digest(blocks) == source["normalized_tsv_sha256"] == NORMALIZED_SHA256,
            "canonical normalized TSV checksum mismatch")
    expected_urls = [f"{SOURCE}/v1/export-blocks?from={start}&to={min(start + 999, PAST_LAST)}"
                     for start in range(FIRST - 1, PAST_LAST + 1, 1000)]
    require([page["url"] for page in source["pages"]] == expected_urls,
            "unexpected canonical export page coverage")
    for page in source["pages"]:
        digest = page["csv_sha256"]
        require(len(digest) == 64 and all(c in "0123456789abcdef" for c in digest),
                "invalid CSV checksum")
    return blocks[1:-1]


def ud(value):
    return f"{value:,}".replace(",", ".")


def partitions(blocks):
    return [blocks[index:index + CHUNK_SIZE] for index in range(0, len(blocks), CHUNK_SIZE)]


def chunk_name(blocks):
    return f"heights-{blocks[0]['height']}-{blocks[-1]['height']}.hoon"


def render_chunk(blocks):
    # Source-debug wrappers prevent hoonc's ordinary literal-cons folding.
    # Scope !. to inert data; the shared decoder and map builder keep diagnostics.
    lines = [CHUNK_HEADER.rstrip("\n"),
             f"::  Canonical realnet IDs at heights {blocks[0]['height']}..{blocks[-1]['height']}.",
             "::  Inert height/cord literals only; diagnostics are disabled only for this data.",
             "^-  (list [@ud @t])", "!."]
    for index, block in enumerate(blocks):
        prefix = ":~  " if index == 0 else "    "
        lines.append(f"{prefix}[%{ud(block['height'])} '{block['hash']}']")
    lines.append("==")
    return "\n".join(lines) + "\n"


def render(source, blocks):
    chunks = partitions(blocks)
    lines = ["::  Canonical realnet Legacy AI checkpoint IDs; no proof or fork-choice state.",
             "::  Generated by scripts/generate-legacy-ai-checkpoints.py.",
             f"::  Canonical history retrieved {source['retrieved_date']}.",
             "::  Pinned heights: 126000..154499 inclusive (28500 entries).",
             "::  Source heights: 125999..154500; neighbors validate parent links only.",
             "::  SHA256 of height TAB base58-id TAB base58-parent LF:",
             f"::  {NORMALIZED_SHA256}",
             "::  Literal chunks contain at most 1000 explicit height/cord pairs each.",
             "::  One shared decoder and one gas construct the immutable map at import.",
             "::  Consensus lookups use the imported value, not per-request conversion.",
             "/=  t  /common/tx-engine", "/=  *  /common/zoon"]
    for chunk in chunks:
        alias = f"pins-{chunk[0]['height']}"
        lines.append(f"/=  {alias}  /dat/{CHUNK_DIRECTORY}/{Path(chunk_name(chunk)).stem}")
    lines.extend(["^-  (z-map page-number:t hash:t)",
                  "%-  ~(gas z-by *(z-map page-number:t hash:t))",
                  "^-  (list [page-number:t hash:t])",
                  "%+  turn",
                  "  ^-  (list [page-number:t @t])",
                  "  %-  zing",
                  "  ^-  (list (list [@ud @t]))"])
    for index, chunk in enumerate(chunks):
        prefix = "  :~  " if index == 0 else "      "
        lines.append(f"{prefix}pins-{chunk[0]['height']}")
    lines.extend(["  ==", "|=  [height=page-number:t encoded=@t]",
                  "^-  [page-number:t hash:t]",
                  "[height (from-b58:hash:t encoded)]"])
    return "\n".join(lines) + "\n"


def owned_chunks(directory):
    if not directory.exists():
        return set()
    return {path for path in directory.iterdir()
            if CHUNK_NAME.fullmatch(path.name) and not path.is_symlink()
            and path.is_file() and path.read_bytes().startswith(CHUNK_HEADER.encode("utf-8"))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--source", type=Path, help="offline canonical JSON artifact")
    mode.add_argument("--fetch-source", type=Path, help="explicitly fetch canonical CSV pages and save JSON")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="compare root and all chunks, including stale owned chunks")
    args = parser.parse_args()
    if args.fetch_source:
        source = fetch_source()
    else:
        source = json.loads(args.source.read_text(encoding="utf-8"))
    blocks = validate(source)
    if args.fetch_source:
        args.fetch_source.write_text(json.dumps(source, indent=2) + "\n", encoding="utf-8")
    generated = render(source, blocks).encode("utf-8")
    chunk_directory = args.output.parent / CHUNK_DIRECTORY
    outputs = {args.output: generated}
    outputs.update({chunk_directory / chunk_name(chunk): render_chunk(chunk).encode("utf-8")
                    for chunk in partitions(blocks)})
    owned = owned_chunks(chunk_directory)
    stale = owned - outputs.keys()
    if args.check:
        problems = [f"generated Hoon module missing or differs: {path}"
                    for path, content in outputs.items()
                    if not path.is_file() or path.read_bytes() != content]
        problems.extend(f"stale owned Hoon chunk: {path}" for path in sorted(stale))
        require(not problems, "\n".join(problems))
    else:
        for path in outputs:
            if path == args.output:
                continue
            require(not path.is_symlink(), f"refusing to overwrite symlink: {path}")
            require(not path.exists() or path in owned,
                    f"refusing to overwrite unowned chunk: {path}")
        chunk_directory.mkdir(parents=True, exist_ok=True)
        for path, content in outputs.items():
            path.write_bytes(content)
        for path in sorted(stale):
            path.unlink()
    print(f"source normalized TSV SHA256: {NORMALIZED_SHA256}")
    print(f"root output SHA256: {hashlib.sha256(generated).hexdigest()}")
    print(f"{len(blocks)} checkpoints; {len(outputs)} files; "
          f"{sum(map(len, outputs.values()))} output bytes; {args.output}")


if __name__ == "__main__":
    main()
